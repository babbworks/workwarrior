#!/usr/bin/env bash
# Generate tasks/INDEX.md from the task cards themselves.
#
# The card `Status:` field is the ONLY source of truth. This script derives the
# index from it so the two can never disagree again.
#
# HARD RULE: a card whose Status cannot be parsed is a FATAL ERROR, never a
# silent omission. Silently skipping unparseable cards is what hid 15 cards from
# `wwctl task-status` and let the board drift for months.
#
# Usage:
#   gen-index.sh            Rewrite tasks/INDEX.md
#   gen-index.sh --check    Exit 1 if INDEX.md is stale (no write). Gate-able.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
source "${SCRIPT_DIR}/common.sh"

CARDS_DIR="${CODEX_ROOT}/tasks/cards"
INDEX="${CODEX_ROOT}/tasks/INDEX.md"
MODE="${1:-write}"

require_dir "${CARDS_DIR}"

# Bucket a raw status string. Everything before the first em-dash/paren is the verb.
bucket() {
  local raw
  raw="$(echo "${1}" | tr '[:upper:]' '[:lower:]')"
  case "${raw}" in
    complete*|closed*)  echo "complete" ;;
    verified*)          echo "verified" ;;
    in-progress*)       echo "in-progress" ;;
    in-review*)         echo "in-review" ;;
    blocked*)           echo "blocked" ;;
    parked*)            echo "parked" ;;
    deferred*)          echo "deferred" ;;
    pending*|open*)     echo "pending" ;;
    *)                  echo "UNKNOWN" ;;
  esac
}

TMP="$(mktemp)"
trap 'rm -f "${TMP}" "${TMP}.rows"' EXIT

# --- Parse every card. Any failure to parse is fatal. ---------------------
: > "${TMP}.rows"
unparseable=()
for card in "${CARDS_DIR}"/TASK-*.md; do
  [[ -e "${card}" ]] || continue
  id="$(basename "${card}" .md)"

  status="$(grep -m1 -E '^Status:' "${card}" 2>/dev/null | sed -E 's/^Status:[[:space:]]*//' || true)"
  if [[ -z "${status}" ]]; then
    unparseable+=("${id} — no parseable '^Status:' field")
    continue
  fi

  b="$(bucket "${status}")"
  if [[ "${b}" == "UNKNOWN" ]]; then
    unparseable+=("${id} — unrecognised status: '${status}'")
    continue
  fi

  title="$(grep -m1 -E '^## TASK-' "${card}" | sed -E 's/^## [^:]+:[[:space:]]*//' || true)"
  [[ -n "${title}" ]] || title="(untitled)"
  dep="$(grep -m1 -E '^Depends on:' "${card}" | sed -E 's/^Depends on:[[:space:]]*//' | cut -c1-40 || true)"

  # short status: first clause only, for table legibility
  short="$(echo "${status}" | sed -E 's/[[:space:]]*[—(].*$//' | cut -c1-10)"
  printf '%s\t%s\t%s\t%s\t%s\n' "${b}" "${id}" "${title}" "${short}" "${dep}" >> "${TMP}.rows"
done

if (( ${#unparseable[@]} > 0 )); then
  echo "ERROR: ${#unparseable[@]} card(s) have no usable Status — refusing to write a partial index." >&2
  printf '  %s\n' "${unparseable[@]}" >&2
  echo "" >&2
  echo "Every card MUST carry a canonical '^Status:' line (see dev/templates/task-card.md)." >&2
  exit 1
fi

total="$(wc -l < "${TMP}.rows" | tr -d ' ')"
count_of() { grep -cP "^$1\t" "${TMP}.rows" 2>/dev/null || true; }

emit_section() {
  local b="$1" heading="$2" n
  n="$(count_of "${b}")"
  [[ "${n}" -gt 0 ]] || return 0
  echo "## ${heading} (${n})"
  echo ""
  echo "| Card | Goal | Depends on |"
  echo "|---|---|---|"
  # shellcheck disable=SC2034
  while IFS=$'\t' read -r bb id title short dep; do
    [[ "${bb}" == "${b}" ]] || continue
    echo "| [${id}](cards/${id}.md) | ${title} | ${dep:-—} |"
  done < <(sort -t$'\t' -k2,2 "${TMP}.rows")
  echo ""
}

{
  echo "# Task Card Index"
  echo ""
  echo "<!-- GENERATED by dev/scripts/gen-index.sh — DO NOT EDIT BY HAND."
  echo "     The card 'Status:' field is the source of truth. Regenerate with: wwctl index -->"
  echo ""
  echo "Generated: $(date +%Y-%m-%d) · ${total} cards in \`tasks/cards/\`"
  echo ""
  echo "| Bucket | Count |"
  echo "|---|---|"
  for b in in-progress in-review blocked verified pending parked deferred complete; do
    n="$(count_of "${b}")"
    [[ "${n}" -gt 0 ]] && echo "| ${b} | ${n} |"
  done
  echo ""
  echo "---"
  echo ""
  emit_section "in-progress" "In Progress"
  emit_section "in-review"   "In Review"
  emit_section "blocked"     "Blocked"
  emit_section "verified"    "Verified — awaiting merge"
  emit_section "pending"     "Pending"
  emit_section "parked"      "Parked"
  emit_section "deferred"    "Deferred"

  echo "## Complete ($(count_of complete))"
  echo ""
  while IFS=$'\t' read -r bb id title short dep; do
    [[ "${bb}" == "complete" ]] || continue
    echo "- **${id}** — ${title}"
  done < <(sort -t$'\t' -k2,2 "${TMP}.rows")
} > "${TMP}"

if [[ "${MODE}" == "--check" ]]; then
  if ! diff -q "${INDEX}" "${TMP}" >/dev/null 2>&1; then
    echo "FAIL  tasks/INDEX.md is stale — a card Status changed without regenerating." >&2
    echo "      Run: wwctl index" >&2
    diff -u "${INDEX}" "${TMP}" | head -30 >&2 || true
    exit 1
  fi
  echo "PASS  tasks/INDEX.md is in sync with ${total} cards"
  exit 0
fi

mv "${TMP}" "${INDEX}"
trap - EXIT
rm -f "${TMP}.rows"
echo "Wrote ${INDEX} — ${total} cards"
